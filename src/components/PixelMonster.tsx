export function PixelMonster({
  spriteId,
  attribute,
  size = 112,
  isBoss = false,
}: PixelMonsterProps) {
  const grid = SPRITE_GRIDS[spriteId] ?? SPRITE_GRIDS.slime;
  const attrColor = ATTR_META[attribute].color;
  const accentColor = isBoss ? "#D4AF37" : "#C93A2B";

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      className="pixelated select-none"
      aria-hidden="true"
    >
      {grid.map((row, y) =>
        row.split("").map((ch, x) => {
          if (ch === ".") return null;
          const fill =
            ch === "#"
              ? attrColor
              : ch === "@"
                ? "#ECE6D8"
                : accentColor;
          return <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={fill} />;
        })
      )}
    </svg>
  );
}
